import { writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE_URL = 'https://storage.googleapis.com/play_public/supported_devices.html';
const OUTPUT_PATH = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../app/shared/lib/androidDeviceModelNames.generated.ts',
);

const NAMED_HTML_ENTITIES = {
  amp: '&',
  apos: "'",
  gt: '>',
  lt: '<',
  quot: '"',
};

const decodeHtml = (value) =>
  value
    .replace(/<[^>]*>/g, '')
    .replace(/&#(x?[0-9a-f]+);|&(amp|apos|gt|lt|quot);/gi, (match, numeric, named) => {
      if (numeric) {
        const radix = numeric[0].toLowerCase() === 'x' ? 16 : 10;
        const codePoint = Number.parseInt(numeric.replace(/^x/i, ''), radix);
        return Number.isInteger(codePoint) && codePoint <= 0x10ffff
          ? String.fromCodePoint(codePoint)
          : match;
      }
      return NAMED_HTML_ENTITIES[named.toLowerCase()];
    })
    .replace(/\s+/g, ' ')
    .trim()
    .normalize('NFC');

const normalizeModelKey = (model) => model.replace(/\s+/g, ' ').trim().toLowerCase();

const response = await fetch(SOURCE_URL);
if (!response.ok) {
  throw new Error(`Could not download the Google Play device catalog: HTTP ${response.status}`);
}

const html = await response.text();
const namesByModel = new Map();

for (const rowMatch of html.matchAll(/<tr[^>]*>([\s\S]*?)<\/tr>/gi)) {
  const cells = [...rowMatch[1].matchAll(/<td[^>]*>([\s\S]*?)<\/td>/gi)]
    .map((cellMatch) => decodeHtml(cellMatch[1]));

  if (cells.length !== 4) continue;

  const marketingName = cells[1];
  const model = cells[3];
  if (!marketingName || !model) continue;

  const modelKey = normalizeModelKey(model);
  const names = namesByModel.get(modelKey) ?? new Map();
  names.set(marketingName.toLowerCase(), marketingName);
  namesByModel.set(modelKey, names);
}

const entries = [];
for (const [modelKey, names] of namesByModel) {
  // A few generic model codes are reused by unrelated manufacturers. Leaving
  // those identifiers unchanged is more accurate than choosing the wrong name.
  if (names.size !== 1) continue;

  const marketingName = names.values().next().value;
  if (marketingName.toLowerCase() === modelKey) continue;
  entries.push([modelKey, marketingName]);
}

entries.sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0));

if (entries.length < 10_000) {
  throw new Error(
    `Only ${entries.length} useful model names were parsed; the catalog format may have changed.`,
  );
}

const generatedSource = `/**
 * Generated from the public Google Play supported-device catalog.
 *
 * Run \`npm run generate:android-device-names\` to refresh this file.
 * Only unambiguous identifiers whose marketing name differs from the raw
 * model are included. Do not edit this file manually.
 *
 * Source: ${SOURCE_URL}
 */
export const ANDROID_DEVICE_MODEL_NAMES: Readonly<Record<string, string>> = Object.freeze({
${entries.map(([model, name]) => `    ${JSON.stringify(model)}: ${JSON.stringify(name)},`).join('\n')}
});
`;

await writeFile(OUTPUT_PATH, generatedSource, 'utf8');
console.log(`Wrote ${entries.length.toLocaleString()} Android device names to ${OUTPUT_PATH}`);
